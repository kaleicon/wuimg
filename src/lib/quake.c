static struct palette * get_quake_pal(void) {
	struct palette *pal = palette_new();
	if (pal) {
		palette_from_rgb8(pal, QUAKE_RGB, sizeof(QUAKE_RGB)/3);
		pal->color[255].a = 0x00;
	}
	return pal;
}

